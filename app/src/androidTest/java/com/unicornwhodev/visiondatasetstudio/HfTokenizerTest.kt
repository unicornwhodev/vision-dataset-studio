package com.unicornwhodev.visiondatasetstudio

import androidx.test.platform.app.InstrumentationRegistry
import com.unicornwhodev.visiondatasetstudio.data.json.StudioJson
import com.unicornwhodev.visiondatasetstudio.domain.inference.BytePairTokenizer
import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File

class HfTokenizerTest {
    @Test fun nativeEncodingMatchesPinnedHuggingFaceTokenizer() {
        val root=File(InstrumentationRegistry.getInstrumentation().targetContext.filesDir,"hf-runtime-fixture")
        val reference=File(root,"tokenizer-reference.json")
        assumeTrue("Stage tokenizer reference generated by Hugging Face tokenizers",reference.isFile)
        val data=StudioJson.moshi.adapter(Any::class.java).fromJson(reference.readText()) as Map<*,*>
        var count=0
        for(family in listOf("tinyclip","florence2")) {
            val tokenizer=BytePairTokenizer(File(root,"$family/processor/tokenizer.json"))
            val pad=if(family=="tinyclip")49407 else 1
            for(row in data[family] as List<*>) {
                val item=row as Map<*,*>;val text=item["text"] as String
                val expected=(item["ids"] as List<*>).map{(it as Number).toInt()}.toIntArray()
                val (ids,mask)=tokenizer.encode(text,77,pad)
                assertArrayEquals("$family: $text",expected,ids.take(mask.sum()).toIntArray())
                assertTrue(ids.drop(expected.size).all{it==pad})
                if(family=="florence2")assertEquals(item["decoded"],tokenizer.decode(expected.toList()))
                count++
            }
        }
        File(root,"android-tokenizer-result.json").writeText("{\"encoding_cases\":$count,\"florence_decode_cases\":8,\"success\":true}")
    }
}
